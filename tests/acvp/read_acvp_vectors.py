import json
import subprocess
import sys
import tempfile
import time
from enum import Enum
from functools import cache
from pathlib import Path

ACVP_DIR = Path(__file__).resolve().parent
REGISTRATIONS = ACVP_DIR / "registrations"

# Shared with the ACVP server's container, mounted at /work (see
# server/docker-compose.yml).
WORK_DIR = ACVP_DIR / "server" / "work"


class TestType(Enum):
    # Algorithm Functional Test: independent key/pt/ct vectors, checked in isolation.
    AFT = "AFT"
    # Monte Carlo Test: a chained ~1000-iteration loop per seed, with the key
    # itself mutated periodically; only 100 checkpoint snapshots are given in
    # resultsArray, so the implementation must reproduce the inner loop.
    MCT = "MCT"
    # Variable Output Test (SHAKE only): AFT-shaped independent vectors, but
    # each specifies its own output length rather than the fixed one AFT
    # groups use.
    VOT = "VOT"


def _exec(command: list[str]) -> bytes:
    """Runs `command` inside the ACVP server's container (which must already be
    running, see `pixi run acvp-up`) and returns its stdout."""
    compose_file = ACVP_DIR / "server" / "docker-compose.yml"
    try:
        run = subprocess.run(
            ["docker", "compose", "-f", str(compose_file), "exec", "-T", "acvp-server", *command],
            capture_output=True,
            # Generating a vector set takes ~6s (the CLI waits 5s before
            # collecting results from the Orleans node); a hung node (e.g.
            # after the Docker VM was suspended) should fail the test rather
            # than block it forever.
            timeout=300,
        )
    except subprocess.TimeoutExpired as e:
        raise RuntimeError(
            f"`{' '.join(command)}` timed out on the ACVP server; restart it "
            "with `pixi run acvp-up --force-recreate`"
        ) from e
    if run.returncode != 0:
        raise RuntimeError(
            f"`{' '.join(command)}` failed on the ACVP server (is it running? "
            f"`pixi run acvp-up`):\n{run.stdout.decode()}{run.stderr.decode()}"
        )
    return run.stdout


@cache
def _generate(vector_set: str) -> tuple[dict, dict]:
    # Cached per process: a test file typically loads the same vector set
    # several times (AFT and MCT, sync and async backends), and every
    # generation draws a fresh, random set.
    registration = (REGISTRATIONS / f"{vector_set}.json").read_bytes()

    # The CLI reads the registration from a file and writes the vector set
    # next to it, so give it a scratch directory both sides can see.
    # The test runner only prints results once a whole file is done, so report
    # progress here; otherwise a test file looks stuck while it waits ~6s per
    # vector set.
    print(f"ACVP: generating {vector_set}...", end="", file=sys.stderr, flush=True)
    start = time.monotonic()
    with tempfile.TemporaryDirectory(dir=WORK_DIR) as work:
        (Path(work) / "registration.json").write_bytes(registration)
        _exec(
            [
                "dotnet",
                "/app/genval/NIST.CVP.ACVTS.Generation.GenValApp.dll",
                "-g",
                f"/work/{Path(work).name}/registration.json",
            ]
        )
        prompt = json.loads((Path(work) / "prompt.json").read_text())
        expected = json.loads((Path(work) / "expectedResults.json").read_text())
    print(f" done in {time.monotonic() - start:.1f}s", file=sys.stderr, flush=True)
    return prompt, expected


def _result_index(expected: dict) -> dict[int, dict]:
    index: dict[int, dict] = {}
    for group in expected.get("testGroups", []):
        for tc in group.get("tests", []):
            index[tc["tcId"]] = tc
    return index


def load(vector_set: str, test_type: TestType) -> list[dict]:
    # `vector_set` names a registration in registrations/, e.g.
    # "ACVP-AES-ECB". No AFT/MCT-specific field extraction or renaming
    # (pt_hex/ct_hex/is_encrypt/...): each record is just the raw group,
    # test-case, and expected-result dicts as generated by the server, keyed by
    # tcId. Interpretation of these fields happens on the Mojo side.
    prompt, expected = _generate(vector_set)
    results = _result_index(expected)

    records: list[dict] = []
    for group in prompt.get("testGroups", []):
        if group["testType"] != test_type.value:
            continue
        group_fields = {k: v for k, v in group.items() if k != "tests"}
        for tc in group["tests"]:
            records.append({
                "group": group_fields,
                "test": tc,
                "expected": results.get(tc["tcId"], {}),
            })
    return records
